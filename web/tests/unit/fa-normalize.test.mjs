// تست واحد یکسان‌سازی متن فارسی (src/lib/text/fa-normalize.ts). docs/infoyaarchin.md بخش ۴۰.
import { normalizeFa as n } from "../../src/lib/text/fa-normalize.ts";

let fails = 0,
  c = 0;
const eq = (input, want) => {
  c++;
  const got = n(input);
  if (got !== want) {
    fails++;
    console.log(`FAIL ${JSON.stringify(input)} → ${JSON.stringify(got)} (want ${JSON.stringify(want)})`);
  }
};
const Z = "‌";

// حرف و رقم عربی
eq("كيف و مي", "کیف و می");
eq("٢٥ عدد", "۲۵ عدد");
// می / نمی
eq("این درب بسته می شود", `این درب بسته می${Z}شود`);
eq("خاموش نمی کند", `خاموش نمی${Z}کند`);
eq("میشود", `می${Z}شود`);
eq("نمیتوان", `نمی${Z}توان`);
eq("میخواهد", `می${Z}خواهد`);
// مبهم‌ها دست نمی‌خورند
eq("میز چوبی", "میز چوبی");
eq("میدان", "میدان");
eq("میوه و میلیون و میزان", "میوه و میلیون و میزان");
eq("می", "می");
eq("قدیمی شود", "قدیمی شود");
eq("کمی کند است", "کمی کند است");
eq("«می شود»", `«می${Z}شود»`);
eq("آب ها", `آب${Z}ها`);
// جمع
eq("محصول ها", `محصول${Z}ها`);
eq("ویژگی های اصلی", `ویژگی${Z}های اصلی`);
eq("خانه ها", `خانه${Z}ها`);
eq("تنها", "تنها");
// تر / ترین
eq("بزرگ تر و سبک ترین", `بزرگ${Z}تر و سبک${Z}ترین`);
eq("دختر", "دختر");
// ای / ام بعد از «ه»
eq("خانه ای کوچک", `خانه${Z}ای کوچک`);
eq("نامه ام", `نامه${Z}ام`);
eq("کتاب ای", "کتاب ای");
// ترکیب‌های رایج (بخش ۴۱)
eq("زیرسیگاری یکبار مصرف", `زیرسیگاری یک${Z}بار مصرف`);
eq("یکباره رفت", "یکباره رفت");
eq("یک بار امتحان کنید", "یک بار امتحان کنید");
eq("زیر سیگاری خود خاموش کن", `زیرسیگاری خودخاموش${Z}کن`);
eq("خودخاموشکن", `خودخاموش${Z}کن`);
eq("ژل خاموش کننده", `ژل خاموش${Z}کننده`);
eq("ضد آب و ضد زنگ", "ضدآب و ضدزنگ");
eq(`ضد${Z}لغزش`, "ضدلغزش");
eq("ضد", "ضد");
eq("قابل حمل و قابلشستشو", `قابل${Z}حمل و قابل${Z}شستشو`);
eq("قابل توجه", "قابل توجه");
eq("بی صدا و بیسیم و بی دود", `بی${Z}صدا و بی${Z}سیم و بی${Z}دود`);
eq("بیمه و بیرون", "بیمه و بیرون");
eq("چند منظوره و چند کاره", "چندمنظوره و چندکاره");
eq("دست ساز و سبک وزن", `دست${Z}ساز و سبک${Z}وزن`);
eq("زیر سیگاری ها", `زیرسیگاری${Z}ها`);

// فاصله‌ها
eq("دو  فاصله   و تب\tاینجا", "دو فاصله و تب اینجا");
eq("پایان .", "پایان.");
eq("یک ، دو ؛ سه ؟", "یک، دو؛ سه؟");
eq("( داخل )", "(داخل)");
eq("  سطر اول  \n\n\n\n  سطر دوم ", "سطر اول\n\nسطر دوم");
eq(`نیم ${Z} فاصله`, `نیم${Z}فاصله`);
eq(`دو${Z}${Z}تایی`, `دو${Z}تایی`);
// متن انگلیسی و عدد دست نمی‌خورد
eq("Size 9x9 cm, 25 pcs.", "Size 9x9 cm, 25 pcs.");
// بی‌اثر روی متن درست (idempotent)
const good = `زیرسیگاری یک${Z}بار مصرف با ژل خاموش${Z}کننده؛ بوی سیگار را کم می${Z}کند و برای خانه${Z}ها مناسب است.`;
eq(good, good);
eq(n(n("محصول ها می شود")), `محصول${Z}ها می${Z}شود`);

console.log(`${c} checks${fails ? `, ${fails} FAILED` : ", ALL PASSED"}`);
process.exitCode = fails ? 1 : 0;
