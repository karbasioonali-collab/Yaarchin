export type SpecFa = { labelFa: string; valueFa: string; unit: string; translated: { label: boolean; value: boolean } };

// «9*9*3.1cm» / «25 pieces» / «0.005 kg» ← عدد و واحد جدا
function splitUnit(value: string): { value: string; unit: string } | null {
  const m = /^\s*([\d.,]+(?:\s*[*x×]\s*[\d.,]+){0,2})\s*([a-zA-Z]+)\s*$/.exec(value);
  if (!m || !UNIT_FA[m[2].toLowerCase()]) return null;
  return { value: m[1].replace(/\s*[*x×]\s*/g, "×"), unit: UNIT_FA[m[2].toLowerCase()] };
}

// ترجمه‌ی یک ردیف مشخصات از واژه‌نامه؛ هرچه پیدا نشد همان انگلیسی می‌ماند (translated=false) تا انسان یا AI ترجمه کند
export function translateSpec(name: string, value: string): SpecFa {
  const labelFa = ATTR_FA[norm(name)];
  const u = splitUnit(value);
  if (u) return { labelFa: labelFa ?? name, valueFa: u.value, unit: u.unit, translated: { label: !!labelFa, value: true } };
  const parts = value.split(/\s*[,،/;]\s*/).filter(Boolean);
  const fa = parts.map((x) => VALUE_FA[norm(x)]);
  const all = parts.length > 0 && fa.every(Boolean);
  return { labelFa: labelFa ?? name, valueFa: all ? fa.join("، ") : value, unit: "", translated: { label: !!labelFa, value: all } };
}
