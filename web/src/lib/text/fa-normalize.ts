const STEM_RE = STEMS.sort((a, b) => b.length - a.length).join("|");
// «ها/های» جمع، «تر/ترین»، «ای/ام/ایم/اید/اش» بعد از «ه»
const PLURAL = "ها|های|هایی|هایم|هایت|هایش|هایمان|هایتان|هایشان";
const END = `(?=$|[^${FA}‌])`;
const START = `(^|[^${FA}‌])`;

export function normalizeFa(input: string): string {
  let s = input
    // حرف و رقم عربی ← فارسی
    .replace(/ي/g, "ی")
    .replace(/ى/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[٠-٩]/g, (d) => String.fromCharCode(d.charCodeAt(0) - 0x0660 + 0x06f0))
    // تب و فاصله‌ی غیرشکستنی ← فاصله
    .replace(/[\t ]/g, " ");

  // «می شود» / «نمی کند» ← نیم‌فاصله؛ «میشود» (چسبیده) هم
  s = s.replace(new RegExp(`${START}(ن?می) +(?=(?:${STEM_RE})[${FA}]*${END})`, "g"), `$1$2${ZWNJ}`);
  s = s.replace(new RegExp(`${START}(ن?می)(?=(?:${STEM_RE})[${FA}]*${END})`, "g"), `$1$2${ZWNJ}`);
  // «محصول ها» ← «محصول‌ها»
  s = s.replace(new RegExp(`([${FA}]) +(${PLURAL})${END}`, "g"), `$1${ZWNJ}$2`);
  // «بزرگ تر» / «بزرگ ترین» ← نیم‌فاصله
  s = s.replace(new RegExp(`([${FA}]) +(ترین|تر)${END}`, "g"), `$1${ZWNJ}$2`);
  // «خانه ای» / «خانه ام» ← «خانه‌ای»
  s = s.replace(new RegExp(`(ه) +(ای|ام|ایم|اید|اش)${END}`, "g"), `$1${ZWNJ}$2`);

  return (
    s
      // نیم‌فاصله‌ی تکراری یا کنار فاصله
      .replace(/‌{2,}/g, ZWNJ)
      .replace(/ *‌ */g, ZWNJ)
      // فاصله‌های پشت‌سرهم (نه شکستن خط)
      .replace(/ {2,}/g, " ")
      // فاصله‌ی قبل از نشانه‌ها و بعد از پرانتز/گیومه‌ی باز
      .replace(/ +([.،,؛;:!؟?)\]»])/g, "$1")
      .replace(/([(\[«]) +/g, "$1")
      // سر و ته هر خط، و بیش از یک خط خالی
      .split("\n")
      .map((l) => l.trim())
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trim()
  );
}
