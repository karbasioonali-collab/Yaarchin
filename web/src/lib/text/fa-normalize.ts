const FA = "؀-ۿ";
// «می»/«نمی» فقط پیش از این ریشه‌های رایج فعل (ریشه‌ی حال و گذشته)؛ «دان» نیست (میدان)، «ز» و «خ» نیستند (میز، میخ)
